@documented(
    ProvenanceRecord(
        identifier="PSC-VII-T01",
        title="Finite quantum seed orbit",
        status=ClaimStatus.PROVED,
        source="Paper VII",
        assumptions=("finite observable family", "finite state vector"),
        verification_suite="quantum.seeds",
    )
)
class QuantumSeedSystem:
    """A finite observable algebra acting on one or more quantum seeds."""

    def __init__(
        self,
        observables: Mapping[str, Any] | Sequence[Any],
        seeds: Sequence[Any],
        *,
        tolerance: float = 1e-10,
    ) -> None:
        self._system = SeedSystem(observables, seeds, tolerance=tolerance)

    @property
    def dimension(self) -> int:
        """Return the Hilbert space dimension."""

        return self._system.dimension

    def orbit_basis(self) -> np.ndarray:
        """Return a maximal independent orbit family."""

        return np.asarray(self._system.hull_basis(), dtype=complex)

    def orbit_dimension(self) -> int:
        """Return the dimension generated by the observable orbit."""

        return self._system.hull_dimension()

    def is_generating(self) -> bool:
        """Return whether the seed orbit fills the Hilbert space."""

        return self._system.is_generating()

    def certificate(self) -> Certificate:
        """Return the underlying finite generation certificate."""

        return self._system.generation_certificate()


@documented(
    ProvenanceRecord(
        identifier="PSC-VII-C03",
        title="Local orbit and Schmidt rank",
        status=ClaimStatus.PROVED,
        source="Paper VII",
        assumptions=("finite bipartite pure state",),
        verification_suite="quantum.seeds",
    )
)
def local_orbit_dimension(
    state: Any,
    left_dimension: int,
    right_dimension: int,
    *,
    tolerance: float = 1e-10,
) -> int:
    """Return the orbit dimension under the full left matrix algebra."""

    left = int(left_dimension)
    right = int(right_dimension)
    if isinstance(left_dimension, bool) or isinstance(right_dimension, bool) or left != left_dimension or right != right_dimension:
        raise ValidationError("bipartite dimensions must be integers")
    if left <= 0 or right <= 0:
        raise ValidationError("bipartite dimensions must be positive")
    vector = as_vector(state, dimension=left * right, name="bipartite state")
    matrix = vector.reshape((left, right))
    singular_values = np.linalg.svd(matrix, compute_uv=False)
    rank = int(np.sum(singular_values > tolerance * max(1.0, float(singular_values[0]) if singular_values.size else 1.0)))
    return left * rank


def schmidt_rank(
    state: Any,
    left_dimension: int,
    right_dimension: int,
    *,
    tolerance: float = 1e-10,
) -> int:
    """Return the numerical Schmidt rank of a bipartite pure state."""

    left = int(left_dimension)
    right = int(right_dimension)
    if isinstance(left_dimension, bool) or isinstance(right_dimension, bool) or left != left_dimension or right != right_dimension:
        raise ValidationError("bipartite dimensions must be integers")
    if left <= 0 or right <= 0:
        raise ValidationError("bipartite dimensions must be positive")
    vector = as_vector(state, dimension=left * right, name="bipartite state")
    singular_values = np.linalg.svd(vector.reshape((left, right)), compute_uv=False)
    scale = max(1.0, float(singular_values[0]) if singular_values.size else 1.0)
    return int(np.sum(singular_values > tolerance * scale))


def observable_seed_rank(block_dimensions: Sequence[int], multiplicities: Sequence[int]) -> int:
    """Return the seed rank of a finite semisimple observable algebra."""

    return semisimple_seed_rank(block_dimensions, multiplicities)


def computational_basis_generation(qubits: int) -> tuple[np.ndarray, tuple[np.ndarray, ...], Certificate]:
    """Generate the computational basis from the all zero state by Pauli X addresses."""

    count = int(qubits)
    if isinstance(qubits, bool) or count != qubits or count < 1:
        raise ValidationError("qubits must be a positive integer")
    dimension = 2**count
    seed = np.zeros(dimension, dtype=complex)
    seed[0] = 1
    x = np.array([[0, 1], [1, 0]], dtype=complex)
    identity = np.eye(2, dtype=complex)
    addresses: list[np.ndarray] = []
    basis: list[np.ndarray] = []
    for index in range(dimension):
        factors = [x if (index >> (count - 1 - position)) & 1 else identity for position in range(count)]
        operator = factors[0]
        for factor in factors[1:]:
            operator = np.kron(operator, factor)
        addresses.append(operator)
        basis.append(operator @ seed)
    matrix = np.column_stack(basis)
    residual = float(np.linalg.norm(matrix.conj().T @ matrix - np.eye(dimension)))
    return (
        seed,
        tuple(addresses),
        Certificate(
            valid=residual <= 1e-12,
            exactness=Exactness.NUMERICAL,
            residuals={"basis_orthogonality": residual},
            tolerance=1e-12,
            assumptions_checked=("Pauli X address family",),
            theorem_id="PSC-VII-T04",
            message="Pauli X addresses generate the computational basis",
        ),
    )


