"""Finite Euclidean transfer operators and reflection positivity."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Iterable

import numpy as np

from ..certificates import Certificate, ComputationResult, Exactness
from ..dynamics._linalg import matrix_exponential
from ..exceptions import DimensionError, ValidationError
from ..provenance import ClaimStatus, ProvenanceRecord, documented
from ._validation import as_vector, require_hermitian


@documented(
    ProvenanceRecord(
        identifier="PSC-VII-T56",
        title="Finite reflection positive transfer",
        status=ClaimStatus.PROVED,
        source="Paper VII",
        assumptions=("finite nonnegative Hamiltonian after ground shift",),
        verification_suite="quantum.euclidean",
    )
)
@dataclass(frozen=True, slots=True)
class EuclideanTransfer:
    """A positive Euclidean transfer operator generated by a Hermitian Hamiltonian."""

    hamiltonian: np.ndarray
    lattice_spacing: float
    ground_energy: float
    tolerance: float = 1e-10

    def __init__(
        self,
        hamiltonian: Any,
        lattice_spacing: float,
        *,
        ground_energy: float | None = None,
        tolerance: float = 1e-10,
    ) -> None:
        value = require_hermitian(hamiltonian, tolerance=tolerance, name="Euclidean Hamiltonian")
        spacing = float(lattice_spacing)
        if not np.isfinite(spacing) or spacing <= 0:
            raise ValidationError("lattice_spacing must be positive and finite")
        eigenvalues = np.linalg.eigvalsh(value)
        ground = float(np.min(eigenvalues)) if ground_energy is None else float(ground_energy)
        if not np.isfinite(ground):
            raise ValidationError("ground_energy must be finite")
        shifted = eigenvalues - ground
        if float(np.min(shifted)) < -tolerance:
            raise ValidationError("ground_energy must not exceed the Hamiltonian ground state")
        object.__setattr__(self, "hamiltonian", value)
        object.__setattr__(self, "lattice_spacing", spacing)
        object.__setattr__(self, "ground_energy", ground)
        object.__setattr__(self, "tolerance", float(tolerance))

    @property
    def shifted_hamiltonian(self) -> np.ndarray:
        """Return the nonnegative ground shifted Hamiltonian."""

        return self.hamiltonian - self.ground_energy * np.eye(self.hamiltonian.shape[0])

    def operator(self, steps: int = 1) -> np.ndarray:
        """Return ``exp(-steps*a*(H-E0))``."""

        count = int(steps)
        if isinstance(steps, bool) or count != steps or count < 0:
            raise ValidationError("steps must be a nonnegative integer")
        return matrix_exponential(-count * self.lattice_spacing * self.shifted_hamiltonian)

    def reflection_matrix(self, vectors: Iterable[Any], times: Iterable[int]) -> np.ndarray:
        """Build the finite reflection positive Gram matrix."""

        values = tuple(as_vector(vector, dimension=self.hamiltonian.shape[0], name="reflection vector") for vector in vectors)
        raw_times = tuple(times)
        indices = tuple(int(time) for time in raw_times)
        if not values or len(values) != len(indices):
            raise ValidationError("vectors and times must have one common nonzero length")
        if any(isinstance(raw, bool) or index != raw or index < 0 for raw, index in zip(raw_times, indices, strict=True)):
            raise ValidationError("reflection times must be nonnegative integers")
        result = np.empty((len(values), len(values)), dtype=complex)
        for row, (left, left_time) in enumerate(zip(values, indices, strict=True)):
            for column, (right, right_time) in enumerate(zip(values, indices, strict=True)):
                result[row, column] = np.vdot(left, self.operator(left_time + right_time) @ right)
        return result

    def reflection_certificate(self, vectors: Iterable[Any], times: Iterable[int]) -> ComputationResult[np.ndarray]:
        """Check positive semidefiniteness of the finite reflection matrix."""

        matrix = self.reflection_matrix(vectors, times)
        hermitian = (matrix + matrix.conj().T) / 2
        minimum = float(np.min(np.linalg.eigvalsh(hermitian)))
        return ComputationResult(
            matrix,
            Certificate(
                valid=minimum >= -self.tolerance,
                exactness=Exactness.NUMERICAL,
                residuals={"negative_eigenvalue": max(0.0, -minimum)},
                tolerance=self.tolerance,
                assumptions_checked=("positive Euclidean transfer operator",),
                theorem_id="PSC-VII-T56",
                message="finite Euclidean transfer matrix is reflection positive",
            ),
        )

    @classmethod
    def from_transfer(
        cls,
        transfer: Any,
        lattice_spacing: float,
        *,
        tolerance: float = 1e-10,
    ) -> "EuclideanTransfer":
        """Recover a nonnegative Hamiltonian from a positive definite contraction."""

        value = require_hermitian(transfer, tolerance=tolerance, name="Euclidean transfer operator")
        eigenvalues, eigenvectors = np.linalg.eigh(value)
        if float(np.min(eigenvalues)) <= 0 or float(np.max(eigenvalues)) > 1 + tolerance:
            raise ValidationError("transfer operator must be positive definite and contractive")
        spacing = float(lattice_spacing)
        if spacing <= 0 or not np.isfinite(spacing):
            raise ValidationError("lattice_spacing must be positive and finite")
        hamiltonian = eigenvectors @ np.diag(-np.log(eigenvalues) / spacing) @ eigenvectors.conj().T
        return cls(hamiltonian, spacing, ground_energy=0.0, tolerance=tolerance)


__all__ = ["EuclideanTransfer"]
