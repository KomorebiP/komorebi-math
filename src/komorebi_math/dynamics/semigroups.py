"""Finite matrix semigroups, packet blocks, and refinement defects."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Sequence

import numpy as np

from ..certificates import Certificate, ComputationResult, Exactness
from ..core import PacketOperator, PacketSystem, TransferGraph
from ..exceptions import DimensionError, ValidationError
from ..provenance import ClaimStatus, ProvenanceRecord, documented
from ._linalg import as_square_matrix, matrix_exponential


def _finite_time(value: float, name: str = "time") -> float:
    result = float(value)
    if not np.isfinite(result) or result < 0:
        raise ValidationError(f"{name} must be finite and nonnegative")
    return result


@documented(
    ProvenanceRecord(
        identifier="PSC-VI-D01",
        title="Finite matrix semigroup",
        status=ClaimStatus.DEFINITION,
        source="Paper VI",
        assumptions=("finite square generator",),
        verification_suite="dynamics.semigroups",
    )
)
@dataclass(frozen=True, slots=True)
class MatrixSemigroup:
    """The finite semigroup generated by one square matrix."""

    generator: np.ndarray

    def __post_init__(self) -> None:
        object.__setattr__(self, "generator", as_square_matrix(np.asarray(self.generator), name="generator"))

    @property
    def dimension(self) -> int:
        return int(self.generator.shape[0])

    def at(self, time: float) -> np.ndarray:
        return matrix_exponential(_finite_time(time) * self.generator)

    def operator(self, time: float) -> np.ndarray:
        """Return the semigroup operator at nonnegative ``time``.

        This compatibility name makes the runtime meaning explicit while
        preserving :meth:`at` as the concise primary method.
        """

        return self.at(time)

    def apply(self, time: float, vector: Any) -> np.ndarray:
        value = np.asarray(vector)
        if value.ndim != 1 or value.size != self.dimension:
            raise DimensionError("vector dimension does not match the semigroup generator")
        return self.at(time) @ value

    def resolvent(self, value: complex) -> np.ndarray:
        z = complex(value)
        return np.linalg.inv(z * np.eye(self.dimension, dtype=np.result_type(self.generator, z)) - self.generator)

    def semigroup_certificate(self, first: float, second: float, *, tolerance: float = 1e-10) -> Certificate:
        s = _finite_time(first, "first")
        t = _finite_time(second, "second")
        left = self.at(s + t)
        right = self.at(s) @ self.at(t)
        residual = float(np.linalg.norm(left - right, 2))
        valid = residual <= tolerance * max(1.0, float(np.linalg.norm(left, 2)))
        return Certificate(
            valid=valid,
            exactness=Exactness.NUMERICAL,
            residuals={"semigroup_law": residual},
            tolerance=tolerance,
            assumptions_checked=("finite matrix generator",),
            theorem_id="PSC-VI-T01",
            message="semigroup law verified" if valid else "semigroup law failed",
        )


@documented(
    ProvenanceRecord(
        identifier="PSC-VI-T02",
        title="Packet semigroup convolution",
        status=ClaimStatus.PROVED,
        source="Paper VI",
        assumptions=("finite complete packet family",),
        verification_suite="dynamics.semigroups",
    )
)
@dataclass(frozen=True, slots=True)
class PacketSemigroup:
    """A finite matrix semigroup resolved into packet transfer blocks."""

    semigroup: MatrixSemigroup
    packets: PacketSystem

    def __post_init__(self) -> None:
        if self.packets.dimension != self.semigroup.dimension:
            raise DimensionError("packet dimension does not match the semigroup generator")

    @classmethod
    def from_generator(cls, generator: Any, packets: PacketSystem) -> "PacketSemigroup":
        return cls(MatrixSemigroup(np.asarray(generator)), packets)

    def blocks(self, time: float) -> PacketOperator:
        return PacketOperator.from_operator(self.semigroup.at(time), self.packets)

    def generator_blocks(self) -> PacketOperator:
        return PacketOperator.from_operator(self.semigroup.generator, self.packets)

    def transfer_graph(self, *, tolerance: float = 1e-12) -> TransferGraph:
        return TransferGraph.from_packet_operator(self.generator_blocks(), tolerance=tolerance)

    def convolution_certificate(self, first: float, second: float, *, tolerance: float = 1e-10) -> Certificate:
        s_blocks = self.blocks(first)
        t_blocks = self.blocks(second)
        total_blocks = self.blocks(float(first) + float(second))
        product = s_blocks.compose(t_blocks)
        residual = float(np.linalg.norm(product.reconstruct() - total_blocks.reconstruct(), 2))
        valid = residual <= tolerance * max(1.0, float(np.linalg.norm(total_blocks.reconstruct(), 2)))
        return Certificate(
            valid=valid,
            exactness=Exactness.NUMERICAL,
            residuals={"packet_convolution": residual},
            tolerance=tolerance,
            assumptions_checked=("complete packet family", "finite semigroup"),
            theorem_id="PSC-VI-T02",
            message="packet semigroup convolution verified" if valid else "packet semigroup convolution failed",
        )

    def minimum_transfer_order(self, source: int, target: int, *, tolerance: float = 1e-12) -> int | None:
        graph = self.transfer_graph(tolerance=tolerance)
        if source == target:
            return 0
        for length in range(1, graph.order + 1):
            if graph.paths(source, target, length=length):
                return length
        return None


@documented(
    ProvenanceRecord(
        identifier="PSC-VI-D07",
        title="Semigroup refinement defect",
        status=ClaimStatus.DEFINITION,
        source="Paper VI",
        assumptions=("finite fine and coarse generators", "linear coarsening map"),
        verification_suite="dynamics.semigroups",
    )
)
@dataclass(frozen=True, slots=True)
class SemigroupRefinement:
    """A finite fine to coarse semigroup comparison."""

    coarsen: np.ndarray
    fine_generator: np.ndarray
    coarse_generator: np.ndarray

    def __post_init__(self) -> None:
        coarsen = np.asarray(self.coarsen)
        fine = as_square_matrix(np.asarray(self.fine_generator), name="fine_generator")
        coarse = as_square_matrix(np.asarray(self.coarse_generator), name="coarse_generator")
        if coarsen.ndim != 2 or coarsen.shape != (coarse.shape[0], fine.shape[0]):
            raise DimensionError("coarsening map has incompatible dimensions")
        object.__setattr__(self, "coarsen", coarsen)
        object.__setattr__(self, "fine_generator", fine)
        object.__setattr__(self, "coarse_generator", coarse)

    @property
    def generator_defect(self) -> np.ndarray:
        return self.coarsen @ self.fine_generator - self.coarse_generator @ self.coarsen

    def direct_defect(self, time: float) -> np.ndarray:
        t = _finite_time(time)
        return self.coarsen @ matrix_exponential(t * self.fine_generator) - matrix_exponential(t * self.coarse_generator) @ self.coarsen

    def duhamel(self, time: float, *, quadrature_order: int = 24) -> ComputationResult[np.ndarray]:
        """Evaluate the exact Duhamel integral by Gauss Legendre quadrature."""

        t = _finite_time(time)
        if quadrature_order < 2:
            raise ValidationError("quadrature_order must be at least two")
        nodes, weights = np.polynomial.legendre.leggauss(int(quadrature_order))
        coarse_dim, fine_dim = self.coarsen.shape
        dtype = np.result_type(self.coarsen, self.fine_generator, self.coarse_generator, float)
        integral = np.zeros((coarse_dim, fine_dim), dtype=dtype)
        if t != 0.0:
            mapped = 0.5 * t * (nodes + 1.0)
            for node, weight in zip(mapped, weights, strict=True):
                integral += (
                    0.5
                    * t
                    * weight
                    * matrix_exponential((t - node) * self.coarse_generator)
                    @ self.generator_defect
                    @ matrix_exponential(node * self.fine_generator)
                )
        direct = self.direct_defect(t)
        residual = float(np.linalg.norm(integral - direct, 2))
        tolerance = 1e-9 * max(1.0, float(np.linalg.norm(direct, 2)))
        valid = residual <= tolerance
        return ComputationResult(
            np.real_if_close(integral, tol=1000),
            Certificate(
                valid=valid,
                exactness=Exactness.NUMERICAL,
                residuals={"duhamel_identity": residual},
                tolerance=tolerance,
                assumptions_checked=("finite generators", "Gauss Legendre quadrature"),
                theorem_id="PSC-VI-T08",
                message="Duhamel refinement identity verified" if valid else "Duhamel refinement identity failed",
            ),
        )

    def norm_bound(self, time: float) -> float:
        """Return a direct finite dimensional exponential norm bound."""

        t = _finite_time(time)
        fine_norm = float(np.linalg.norm(self.fine_generator, 2))
        coarse_norm = float(np.linalg.norm(self.coarse_generator, 2))
        return t * np.exp(t * max(fine_norm, coarse_norm)) * float(np.linalg.norm(self.generator_defect, 2))

    def resolvent_defect(self, value: complex) -> ComputationResult[np.ndarray]:
        z = complex(value)
        fine = np.linalg.inv(z * np.eye(self.fine_generator.shape[0]) - self.fine_generator)
        coarse = np.linalg.inv(z * np.eye(self.coarse_generator.shape[0]) - self.coarse_generator)
        formula = coarse @ self.generator_defect @ fine
        direct = self.coarsen @ fine - coarse @ self.coarsen
        residual = float(np.linalg.norm(formula - direct, 2))
        tolerance = 1e-10 * max(1.0, float(np.linalg.norm(direct, 2)))
        return ComputationResult(
            formula,
            Certificate(
                valid=residual <= tolerance,
                exactness=Exactness.NUMERICAL,
                residuals={"resolvent_identity": residual},
                tolerance=tolerance,
                assumptions_checked=("value lies in both resolvent sets",),
                theorem_id="PSC-VI-T10",
                message="resolvent refinement identity verified" if residual <= tolerance else "resolvent refinement identity failed",
            ),
        )


@dataclass(frozen=True, slots=True)
class FiniteSemigroupTower:
    """A finite tower of generators and adjacent coarsening maps."""

    generators: tuple[np.ndarray, ...]
    coarsenings: tuple[np.ndarray, ...]

    def __init__(self, generators: Sequence[Any], coarsenings: Sequence[Any]) -> None:
        matrices = tuple(as_square_matrix(np.asarray(value), name="generator") for value in generators)
        maps = tuple(np.asarray(value) for value in coarsenings)
        if len(matrices) < 1 or len(maps) != len(matrices) - 1:
            raise DimensionError("a tower with n levels requires n minus one coarsening maps")
        for index, coarsen in enumerate(maps):
            expected = (matrices[index].shape[0], matrices[index + 1].shape[0])
            if coarsen.ndim != 2 or coarsen.shape != expected:
                raise DimensionError(f"coarsening map {index} has shape {coarsen.shape}, expected {expected}")
        object.__setattr__(self, "generators", matrices)
        object.__setattr__(self, "coarsenings", maps)

    @property
    def levels(self) -> int:
        return len(self.generators)

    def adjacent(self, level: int) -> SemigroupRefinement:
        if not 0 <= level < self.levels - 1:
            raise ValidationError("adjacent refinement level is out of range")
        return SemigroupRefinement(self.coarsenings[level], self.generators[level + 1], self.generators[level])

    def accumulated_coarsening(self, coarse_level: int, fine_level: int) -> np.ndarray:
        if not 0 <= coarse_level <= fine_level < self.levels:
            raise ValidationError("tower levels must satisfy zero <= coarse_level <= fine_level")
        if coarse_level == fine_level:
            return np.eye(self.generators[coarse_level].shape[0])
        result = self.coarsenings[coarse_level]
        for level in range(coarse_level + 1, fine_level):
            result = result @ self.coarsenings[level]
        return result

    def total_defect(self, coarse_level: int, fine_level: int, time: float) -> np.ndarray:
        coarsen = self.accumulated_coarsening(coarse_level, fine_level)
        return coarsen @ matrix_exponential(time * self.generators[fine_level]) - matrix_exponential(time * self.generators[coarse_level]) @ coarsen

    def certificate(self, *, tolerance: float = 1e-10) -> Certificate:
        residuals = {
            f"level_{level}": float(np.linalg.norm(self.adjacent(level).generator_defect, 2))
            for level in range(self.levels - 1)
        }
        valid = all(value <= tolerance for value in residuals.values())
        return Certificate(
            valid=valid,
            exactness=Exactness.NUMERICAL,
            residuals=residuals,
            tolerance=tolerance,
            assumptions_checked=("finite tower dimensions",),
            theorem_id="PSC-VI-T12",
            message="semigroup tower is exactly compatible" if valid else "semigroup tower has nonzero adjacent defects",
        )


ProjectiveSemigroupTower = FiniteSemigroupTower


def semigroup_refinement_defect(
    coarsen: Any,
    fine_generator: Any,
    coarse_generator: Any,
    time: float | None = None,
    *,
    quadrature_order: int = 24,
) -> SemigroupRefinement | ComputationResult[np.ndarray]:
    """Construct a refinement comparison or evaluate its Duhamel defect."""

    comparison = SemigroupRefinement(
        np.asarray(coarsen),
        np.asarray(fine_generator),
        np.asarray(coarse_generator),
    )
    if time is None:
        return comparison
    return comparison.duhamel(time, quadrature_order=quadrature_order)


