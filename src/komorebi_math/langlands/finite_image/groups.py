"""Small exact finite groups, subgroups, and permutation constructors."""

from __future__ import annotations

from dataclasses import dataclass
from itertools import permutations
from typing import Callable, Generic, Hashable, Iterable, TypeVar

from ..._number_theory import require_integer
from ...certificates import Certificate, Exactness
from ...exceptions import ValidationError

Element = TypeVar("Element", bound=Hashable)


class FiniteGroup(Generic[Element]):
    """A finite group given by an explicit element set and multiplication law."""

    def __init__(
        self,
        elements: Iterable[Element],
        multiply: Callable[[Element, Element], Element],
        identity: Element,
        *,
        name: str = "G",
        validate: bool = True,
        associativity_limit: int = 128,
    ) -> None:
        self.elements = tuple(dict.fromkeys(elements))
        if not self.elements:
            raise ValidationError("a finite group requires at least one element")
        self.element_set = frozenset(self.elements)
        if identity not in self.element_set:
            raise ValidationError("group identity is not in the element set")
        self.multiply = multiply
        self.identity = identity
        self.name = str(name)
        self._inverse: dict[Element, Element] = {}
        if validate:
            for left in self.elements:
                if multiply(identity, left) != left or multiply(left, identity) != left:
                    raise ValidationError("declared identity does not act as an identity")
                candidates = [right for right in self.elements if multiply(left, right) == identity and multiply(right, left) == identity]
                if len(candidates) != 1:
                    raise ValidationError("group element does not have a unique two-sided inverse")
                self._inverse[left] = candidates[0]
                for right in self.elements:
                    if multiply(left, right) not in self.element_set:
                        raise ValidationError("multiplication leaves the finite element set")
            if len(self.elements) <= require_integer(associativity_limit, name="associativity_limit"):
                for a in self.elements:
                    for b in self.elements:
                        for c in self.elements:
                            if multiply(multiply(a, b), c) != multiply(a, multiply(b, c)):
                                raise ValidationError("finite multiplication is not associative")

    @property
    def order(self) -> int:
        """Return the group order."""

        return len(self.elements)

    def inverse(self, element: Element) -> Element:
        """Return the inverse of one element."""

        if element not in self.element_set:
            raise ValidationError("unknown group element")
        if element not in self._inverse:
            candidates = [right for right in self.elements if self.multiply(element, right) == self.identity and self.multiply(right, element) == self.identity]
            if len(candidates) != 1:
                raise ValidationError("group element does not have a unique inverse")
            self._inverse[element] = candidates[0]
        return self._inverse[element]

    def power(self, element: Element, exponent: int) -> Element:
        """Raise one element to an integer power."""

        power = require_integer(exponent, name="exponent")
        if element not in self.element_set:
            raise ValidationError("unknown group element")
        if power < 0:
            return self.power(self.inverse(element), -power)
        result = self.identity
        factor = element
        while power:
            if power & 1:
                result = self.multiply(result, factor)
            factor = self.multiply(factor, factor)
            power >>= 1
        return result

    def generated_subgroup(self, generators: Iterable[Element], *, name: str | None = None) -> "FiniteSubgroup[Element]":
        """Return the subgroup generated by the supplied elements."""

        generator_tuple = tuple(generators)
        if any(generator not in self.element_set for generator in generator_tuple):
            raise ValidationError("subgroup generator is not an element of the parent group")
        closure = {self.identity, *generator_tuple}
        changed = True
        while changed:
            changed = False
            current = tuple(closure)
            for left in current:
                inverse = self.inverse(left)
                if inverse not in closure:
                    closure.add(inverse)
                    changed = True
                for right in current:
                    product_value = self.multiply(left, right)
                    if product_value not in closure:
                        closure.add(product_value)
                        changed = True
        return FiniteSubgroup(self, tuple(element for element in self.elements if element in closure), name=name or "H")

    def subgroup(self, elements: Iterable[Element], *, name: str = "H") -> "FiniteSubgroup[Element]":
        """Validate and return an explicit subgroup."""

        return FiniteSubgroup(self, tuple(elements), name=name)

    def left_coset_representatives(self, subgroup: "FiniteSubgroup[Element]") -> tuple[Element, ...]:
        """Return deterministic representatives of the left cosets."""

        subgroup.require_parent(self)
        covered: set[Element] = set()
        representatives: list[Element] = []
        for representative in self.elements:
            if representative in covered:
                continue
            representatives.append(representative)
            covered.update(self.multiply(representative, h) for h in subgroup.elements)
        return tuple(representatives)

    def double_coset_representatives(
        self,
        left: "FiniteSubgroup[Element]",
        right: "FiniteSubgroup[Element]",
    ) -> tuple[Element, ...]:
        """Return deterministic representatives of ``left \\ G / right``."""

        left.require_parent(self)
        right.require_parent(self)
        covered: set[Element] = set()
        representatives: list[Element] = []
        for representative in self.elements:
            if representative in covered:
                continue
            representatives.append(representative)
            covered.update(
                self.multiply(self.multiply(h, representative), k)
                for h in left.elements
                for k in right.elements
            )
        return tuple(representatives)

    def certificate(self) -> Certificate:
        """Return an exact finite-group axiom certificate.

        Construction-time validation may be skipped for performance or trusted
        callers.  A certificate is a separate proof obligation and therefore
        rechecks closure, identity, unique two-sided inverses, and associativity
        without using the constructor's associativity shortcut.
        """

        closure_failures = 0
        identity_failures = 0
        inverse_failures = 0
        associativity_failures = 0
        evaluation_failures = 0

        def product(left: Element, right: Element) -> Element | None:
            nonlocal evaluation_failures
            try:
                return self.multiply(left, right)
            except Exception:
                evaluation_failures += 1
                return None

        for left in self.elements:
            if product(self.identity, left) != left or product(left, self.identity) != left:
                identity_failures += 1
            candidates = 0
            for right in self.elements:
                lr = product(left, right)
                rl = product(right, left)
                if lr is not None and lr not in self.element_set:
                    closure_failures += 1
                if rl is not None and rl not in self.element_set:
                    closure_failures += 1
                if lr == self.identity and rl == self.identity:
                    candidates += 1
            if candidates != 1:
                inverse_failures += 1

        for a in self.elements:
            for b in self.elements:
                ab = product(a, b)
                if ab is None or ab not in self.element_set:
                    continue
                for c in self.elements:
                    bc = product(b, c)
                    if bc is None or bc not in self.element_set:
                        continue
                    left_value = product(ab, c)
                    right_value = product(a, bc)
                    if left_value != right_value:
                        associativity_failures += 1

        valid = not any(
            (
                closure_failures,
                identity_failures,
                inverse_failures,
                associativity_failures,
                evaluation_failures,
            )
        )
        return Certificate(
            valid=valid,
            exactness=Exactness.EXACT,
            assumptions_checked=(
                "finite explicit element set",
                "closure",
                "two-sided identity",
                "unique two-sided inverses",
                "associativity",
            ),
            diagnostics={
                "name": self.name,
                "order": self.order,
                "closure_failures": closure_failures,
                "identity_failures": identity_failures,
                "inverse_failures": inverse_failures,
                "associativity_failures": associativity_failures,
                "evaluation_failures": evaluation_failures,
                "associativity_triples": self.order ** 3,
            },
            theorem_id="KM-FINITE-GROUP",
            message="valid finite group" if valid else "invalid finite group table",
        )


@dataclass(frozen=True, slots=True)
class FiniteSubgroup(Generic[Element]):
    """A subgroup of one explicit finite parent group."""

    parent: FiniteGroup[Element]
    elements: tuple[Element, ...]
    name: str = "H"

    def __post_init__(self) -> None:
        values = tuple(dict.fromkeys(self.elements))
        if not values or self.parent.identity not in values:
            raise ValidationError("subgroup must contain the parent identity")
        subset = frozenset(values)
        if not subset <= self.parent.element_set:
            raise ValidationError("subgroup contains an element outside the parent group")
        for left in values:
            if self.parent.inverse(left) not in subset:
                raise ValidationError("subgroup is not closed under inverses")
            for right in values:
                if self.parent.multiply(left, right) not in subset:
                    raise ValidationError("subgroup is not closed under multiplication")
        object.__setattr__(self, "elements", tuple(element for element in self.parent.elements if element in subset))

    @property
    def order(self) -> int:
        """Return the subgroup order."""

        return len(self.elements)

    @property
    def index(self) -> int:
        """Return the subgroup index."""

        return self.parent.order // self.order

    @property
    def element_set(self) -> frozenset[Element]:
        """Return the subgroup element set."""

        return frozenset(self.elements)

    def require_parent(self, parent: FiniteGroup[Element]) -> None:
        """Require the declared parent group."""

        if self.parent is not parent:
            raise ValidationError("subgroup belongs to a different parent group object")

    def is_normal(self) -> bool:
        """Return whether the subgroup is normal in its parent."""

        subset = self.element_set
        for g in self.parent.elements:
            inverse = self.parent.inverse(g)
            for h in self.elements:
                if self.parent.multiply(self.parent.multiply(g, h), inverse) not in subset:
                    return False
        return True

    def intersection(self, other: "FiniteSubgroup[Element]", *, name: str = "intersection") -> "FiniteSubgroup[Element]":
        """Return the intersection with another subgroup of the same parent."""

        self.require_parent(other.parent)
        return FiniteSubgroup(self.parent, tuple(element for element in self.elements if element in other.element_set), name=name)

    def conjugate(self, element: Element, *, name: str | None = None) -> "FiniteSubgroup[Element]":
        """Return the conjugate subgroup by one parent element."""

        if element not in self.parent.element_set:
            raise ValidationError("conjugating element is outside the parent group")
        inverse = self.parent.inverse(element)
        values = tuple(self.parent.multiply(self.parent.multiply(element, h), inverse) for h in self.elements)
        return FiniteSubgroup(self.parent, values, name=name or f"{element}{self.name}{element}^-1")


def cyclic_group(order: int) -> FiniteGroup[int]:
    """Return the additive cyclic group of the declared order."""

    n = require_integer(order, name="order")
    if n < 1:
        raise ValidationError("cyclic group order must be positive")
    return FiniteGroup(range(n), lambda left, right: (left + right) % n, 0, name=f"C{n}")


def compose_permutations(left: tuple[int, ...], right: tuple[int, ...]) -> tuple[int, ...]:
    """Compose permutations using function composition ``left after right``."""

    if len(left) != len(right):
        raise ValidationError("permutations have different degrees")
    return tuple(left[right[index]] for index in range(len(left)))


def symmetric_group(degree: int, *, max_order: int = 40320) -> FiniteGroup[tuple[int, ...]]:
    """Return the full symmetric group on a small finite set."""

    n = require_integer(degree, name="degree")
    if n < 1:
        raise ValidationError("symmetric group degree must be positive")
    elements = tuple(permutations(range(n)))
    if len(elements) > require_integer(max_order, name="max_order"):
        raise ValidationError("symmetric group exceeds the declared safety limit")
    identity = tuple(range(n))
    return FiniteGroup(elements, compose_permutations, identity, name=f"S{n}", associativity_limit=48)


